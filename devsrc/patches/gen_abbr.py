USER={'ור"ן':'ורבנו ניסים'}   # תיקונים שהמשתמש כתב בגיליון
NAMES={'רמב"ם':'רַמְבָּם','רמב"ן':'רַמְבָּן','ראב"ד':'רַאֲבָד','רשב"א':'רַשְׁבָּא','ריב"ש':'רִיבָשׁ','מהרי"ל':'מַהֲרִיל','מהרי"ק':'מַהֲרִיק',
'מהרא"י':'מַהֲרַאי','רי"ף':'רִיף','ר"ן':'רַן','הר"ן':'הָרַן','רא"ש':'רֹאשׁ','הרא"ש':'הָרֹאשׁ','רש"י':'רַשִׁי','רשב"ם':'רַשְׁבַּם','ריטב"א':'רִיטְבָּא',
'ראבי"ה':'רַאֲבִיָּה','רשב"ץ':'רַשְׁבַּץ','תשב"ץ':'תַּשְׁבֵּץ','אר"י':'אֲרִי','האר"י':'הָאֲרִי','אריז"ל':'אֲרִיזַ"ל','האריז"ל':'הָאֲרִיזַל',
'מהרש"ל':'מַהַרְשַׁל','רש"ל':'רַשַׁל','חיד"א':'חִידָא','יעב"ץ':'יַעְבֵּץ','ריצב"א':'רִיצְבָּא','ראב"ן':'רַאֲבַן','רא"ם':'רְאֵם','מהר"ל':'מַהֲרַל',
'מהר"ם':'מַהֲרַם','רמ"ה':'רָמָה','הרמ"ה':'הָרָמָה','ריב"ן':'רִיבָן','מוהרנ"ת':'מוֹהַרְנַת','מוהר"ן':'מוֹהֲרַן','אדמו"ר':'אַדְמוֹר','ש"ס':'שַׁס','הש"ס':'הַשַּׁס',
'רמ"א':'רְמָא','אשר"י':'אֲשֵׁרִי','רא"ה':'רָאָה','הרא"ה':'הָרָאָה','מהרש"א':'מַהַרְשָׁא','רד"ק':'רָדָק','רלב"ג':'רַלְבַּג','של"ה':'שְׁלָה',
'חז"ל':'חֲזַ"ל','רז"ל':'רַזַ"ל','ס"מ':'סָמֶךְ מֵם','אריז"ל':'אֲרִיזַל'}
SPECIAL={'יהו"ה':'אֲדֹנָי','ידו"ד':'אֲדֹנָי','אלהי"ם':'אֱלֹקִים','ד"ע':'דֵּעָה'}
D={}
for r in csv.DictReader(open(SRC,encoding='utf-8')):
    k=r['ראשי תיבות']; v=USER.get(k,r['הפירוש להקראה (לתקן / להשלים)']).strip()
    if k in NAMES or k in SPECIAL: continue
    if not v or v=="'" or re.search(r'/|\?|לבדוק|לפי ההקשר|לפי הספר',v): continue
    if re.sub(r'[״"]','',v)==re.sub(r'[״"]','',k): continue   # שם שנקרא כמו שהוא – בלי ניקוד לא מוסיפים
    D[k]=re.sub(r'\s*\(.*?\)\s*','',v).strip()
EXTRA={"סי'":'סִימָן',"ע'":'עַיֵּן',"פ'":'פֶּרֶק','ב"י':'בֵּית יוֹסֵף','ש"ך':'שַׁךְ','ט"ז':'טַז','מג"א':'מָגֵן אַבְרָהָם','ב"ח':'בַּח','ד"מ':'דַּרְכֵי מֹשֶׁה',"ס'":'סֵפֶר',"שו\"ע":'שֻׁלְחָן עָרוּךְ'}
D.update(EXTRA); D.update(NAMES); D.update(SPECIAL)
D={k.replace('"','״'):v.replace('"','').replace('״','') for k,v in D.items()}
json.dump(D,open('abbr_dict.json','w'),ensure_ascii=False,indent=0)
print(len(D))
